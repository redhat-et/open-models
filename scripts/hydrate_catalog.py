#!/usr/bin/env python3
"""Generate catalog.yaml from catalog.slim.yaml.

catalog.slim.yaml is the hand-edited source of truth (comments and all) -
everything that needs judgment: id, host, tier, group, price, status,
base_url, ... catalog.yaml is a generated artifact, like values-targets.yaml
or configs/opencode.json: don't hand-edit it, `make gen` overwrites it.

For every model with a base_url, this always queries the live vLLM
`<base_url>/models` endpoint (the OpenAI-compatible /v1/models route) and
overwrites `served_model` from the response's model id - the live box is the
authority on what it's actually serving, not whatever was last written down.
`context` is filled from max_model_len only if catalog.slim.yaml doesn't
already set it: a box's native max_model_len is not necessarily what we want
to advertise (e.g. rtx5090-fast caps context well below the box's native
max to keep the KV cache from blowing out under concurrency), so an existing
context is treated as a deliberate cap and never raised automatically.

Boxes are routinely powered off to save money, so when a box can't be
reached, hydration falls back to whatever served_model/context is already
sitting in catalog.slim.yaml for that model (leave those in when pausing a
host) and reports it at the end - a warning, not a failure (exit 0): a valid
catalog.yaml still gets written, and `make gen`/`make deploy` must not break
just because e.g. hotaisle-air is deleted right now.

Once every model has been queried, the result is validated and defaulted
through app.catalog's Pydantic schema (tool_call/reasoning default to true,
max_output to 8192, group to the model id, ...) before being written out -
catalog.slim.yaml doesn't need to spell those out for every model. If a
model still has no usable served_model/context at that point (never
reachable, nothing in the slim file), validation fails, catalog.yaml is
left untouched rather than shipping a broken catalog, and this exits 1.

Needs the web app's venv (pydantic, pyyaml) - run via `make gen` or
`scripts/venv-run.sh scripts/hydrate_catalog.py`.

Usage: hydrate_catalog.py [catalog.slim.yaml] [catalog.yaml]
"""
from __future__ import annotations

import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

import yaml
from pydantic import ValidationError

# Other scripts/*.py duplicate a 3-line load_catalog() rather than import
# from web/app - not worth coupling over. A validation schema is different:
# two copies of it *will* drift, so this one script imports the real thing.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "web"))
from app.catalog import Catalog, format_validation_errors  # noqa: E402

TIMEOUT = 10
HEADER = "# generated by scripts/hydrate_catalog.py from catalog.slim.yaml - do not edit\n"


def load(path: Path) -> dict:
    with path.open() as fh:
        return yaml.safe_load(fh)


def fetch_model_info(base_url: str, api_key: str | None) -> dict:
    req = urllib.request.Request(base_url.rstrip("/") + "/models")
    if api_key and api_key != "none":
        req.add_header("Authorization", f"Bearer {api_key}")
    with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
        body = json.load(resp)
    data = body.get("data") or []
    if not data:
        raise ValueError("empty /v1/models response")
    return data[0]


def hydrate(catalog: dict) -> list[str]:
    failed = []
    for model in catalog.get("models", []):
        base_url = model.get("base_url")
        if not base_url or model.get("byo_key"):
            # byo_key (external) endpoints reject keyless probes (401/403);
            # slim holds the authoritative served_model/context for them
            continue
        try:
            info = fetch_model_info(base_url, model.get("api_key"))
        except (urllib.error.URLError, OSError, ValueError) as e:
            failed.append(f"{model.get('id', base_url)}: {e} (kept fallback from slim file)")
            continue
        model["served_model"] = info["id"]
        if model.get("context") is None and info.get("max_model_len"):
            model["context"] = info["max_model_len"]
    return failed


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parent.parent
    slim_path = Path(argv[1]) if len(argv) > 1 else root / "catalog.slim.yaml"
    out_path = Path(argv[2]) if len(argv) > 2 else root / "catalog.yaml"
    catalog = load(slim_path)
    failed = hydrate(catalog)

    try:
        validated = Catalog.model_validate(catalog)
    except ValidationError as e:
        print(f"hydrate_catalog: {slim_path} is invalid, leaving {out_path} untouched:", file=sys.stderr)
        for line in format_validation_errors(e):
            print(f"  {line}", file=sys.stderr)
        return 1
    catalog = validated.model_dump(exclude_none=True)

    out_path.write_text(HEADER + yaml.safe_dump(catalog, sort_keys=False, width=100))
    print(f"wrote {out_path} ({len(catalog.get('models', []))} models)")
    if failed:
        # a valid catalog.yaml was still written (using fallback values), so
        # this is a warning, not a failure - `make gen` must keep going, e.g.
        # while hotaisle-air is routinely powered off. Non-zero here would
        # abort the whole `make gen`/`make deploy` chain over an expected state.
        print("could not reach live endpoint for (used fallback / left as-is):", file=sys.stderr)
        for line in failed:
            print(f"  {line}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
